"""Generate crates/s85-protocol/src/layout_data.rs from key geometry and captured factory layers.

Usage: gen_layout_rs.py layout.json DEFAULT_LAYER.bin FN1_LAYER.bin OUT.rs

* layout.json: from kbini2json.py (your own install of the official app).
* DEFAULT_LAYER.bin / FN1_LAYER.bin: 504-byte SetMatrix payloads for layer 0 and 1, dumped by
  `decode.py --dump` from a capture in which the official app wrote the factory mapping
  (remap one key, then set it back: the app re-sends the whole layer).
"""
import json
import sys


def main():
    if len(sys.argv) != 5:
        raise SystemExit(__doc__)
    layout_json, default_bin, fn1_bin, out = sys.argv[1:]
    lay = json.load(open(layout_json))
    default, fn1 = open(default_bin, "rb").read(), open(fn1_bin, "rb").read()
    assert len(default) == len(fn1) == 504, "layer payloads must be 504 bytes (126 slots x 4)"

    def esc(s):
        return s.replace("\\", "\\\\").replace('"', '\\"')

    lines = ["// @generated by tools/gen_layout_rs.py from the RK S85 key geometry and captured factory layers.",
             "// Do not edit by hand.", "", "use crate::layout::KeyDef;", "",
             "/// Physical keys: label, rectangle (x1, y1, x2, y2) in a 780x300 canvas, matrix slot.",
             "pub static KEYS: &[KeyDef] = &["]
    for k in lay["keys"]:
        x1, y1, x2, y2 = k["rect"]
        if k["label"] == "Wheel":
            x1, y1, x2, y2 = 735, 18, 770, 53  # the knob has no rectangle in KB.ini; place it top-right
        lines.append(f'    KeyDef {{ label: "{esc(k["label"])}", rect: ({x1}, {y1}, {x2}, {y2}), slot: {k["matrix"]} }},')
    lines += ["];", ""]
    for name, data in (("FACTORY_DEFAULT", default), ("FACTORY_FN1", fn1)):
        vals = [int.from_bytes(data[i:i + 4], "big") for i in range(0, 504, 4)]
        lines.append(f"pub static {name}: [u32; crate::keymap::SLOTS] = [")
        for i in range(0, len(vals), 6):
            lines.append("    " + " ".join(f"0x{v:08x}," for v in vals[i:i + 6]))
        lines += ["];", ""]
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", out, len(lay["keys"]), "keys")


if __name__ == "__main__":
    main()
